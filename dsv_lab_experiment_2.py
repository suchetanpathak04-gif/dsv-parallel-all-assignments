"""## Question 38

Generate 100 normal observations with fixed seed; count outliers and clamp to 30–70; compare statistics.
"""

rng = np.random.default_rng(42)
original = rng.normal(50, 12, 100)
outside = (original < 30) | (original > 70)
cleaned = np.where(original < 30, 30, np.where(original > 70, 70, original))
def stats(x):
    return {'mean': x.mean(), 'variance': x.var(), 'std': x.std(), 'min': x.min(), 'max': x.max()}
print('Values outside 30–70:', int(outside.sum()))
print('Original statistics:', stats(original))
print('Cleaned statistics:', stats(cleaned))
# Boundary replacement reduces extremes and constrains the minimum/maximum; mean and spread may change.

"""## Question 39

Combine three branch Series by addition; identify missing values, common quarters, and a separate absent-as-zero result.
"""

branch_a = pd.Series({'Q1': 120, 'Q2': 145, 'Q4': 180})
branch_b = pd.Series({'Q2': 110, 'Q3': 135, 'Q4': 155})
branch_c = pd.Series({'Q1': 95, 'Q3': 125, 'Q4': 140})
ordinary = branch_a + branch_b + branch_c
print('Ordinary addition (missing values propagate):')
print(ordinary)
common = sorted(set(branch_a.index) & set(branch_b.index) & set(branch_c.index))
print('Quarters common to all branches:', common)
print('Combined earnings for common quarters:')
print(ordinary.reindex(common))
zero_filled = branch_a.add(branch_b, fill_value=0).add(branch_c, fill_value=0)
print('Absent records treated as zero:')
print(zero_filled)
# Ordinary addition gives NaN if any branch lacks a quarter; fill_value=0 treats absent records as zero.

